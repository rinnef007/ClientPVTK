// Generates src/net/ProtocolDefine.ts from the decompiled ProtocolDefine.java.
// Usage: node scripts/gen-protocol.mjs <path/to/ProtocolDefine.java>
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-protocol.mjs <ProtocolDefine.java>');
  process.exit(1);
}
const java = readFileSync(src, 'utf8');
const re = /public static final (byte|short|int) (\w+) = (-?\d+);/g;
const lines = [];
for (const m of java.matchAll(re)) lines.push(`  ${m[2]}: ${m[3]},`);
const out = `// AUTO-GENERATED by scripts/gen-protocol.mjs from ProtocolDefine.java. Do not edit.
// CG_* = client -> server, GC_* = server -> client.
export const ProtocolDefine = {
${lines.join('\n')}
} as const;

export type ProtocolName = keyof typeof ProtocolDefine;

/** Heartbeat type sent by MsgHandler.createSystemHeartMsg() every 15s, payload: short mapId. */
export const MSG_HEARTBEAT = ProtocolDefine.CG_SYSTEM_HEART;
`;
writeFileSync(new URL('../src/net/ProtocolDefine.ts', import.meta.url), out);
console.log(`wrote ${lines.length} constants`);
